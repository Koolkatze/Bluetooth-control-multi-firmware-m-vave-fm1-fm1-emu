def generate(path: Path) -> None:
    compressed = base64.b85decode(''.join(DATA))
    values = zlib.decompress(compressed)
    need = WIDTH * HEIGHT + THUMB_WIDTH * THUMB_HEIGHT
    if len(values) != need:
        raise ValueError(f'Bitmap size mismatch: {len(values)} != {need}')
    if any(v >= 64 for v in values):
        raise ValueError('Invalid palette index in image')
    colors = [c for band in PALETTE for c in band]
    out = [
        '/* Generated Blackhole Remote HD bitmap. C99 firmware. */',
        'static const uint16_t bh_art_palette[64] = {',
    ]
    out.extend('    '+', '.join(f'0x{v:04x}' for v in colors[i:i+8])+','
               for i in range(0,len(colors),8))
    out.extend(['};','static const uint8_t bh_art_splash[34560] = {'])
    a=values[:WIDTH*HEIGHT]
    out.extend('    '+', '.join(str(x) for x in a[i:i+30])+','
               for i in range(0,len(a),30))
    out.extend(['};','static const uint8_t bh_art_widget[2816] = {'])
    b=values[WIDTH*HEIGHT:]
    out.extend('    '+', '.join(str(x) for x in b[i:i+30])+','
               for i in range(0,len(b),30))
    out.extend(['};',''])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(out),encoding='utf-8')
    print(f'Blackhole raster: 240x144 + 64x44, {len(compressed)} zlib bytes')
    print(f'Wrote {path}: {path.stat().st_size} UTF-8 bytes')

if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit('usage: generate_blackhole_bitmap.py app/blackhole_bitmap.inc')
    generate(Path(sys.argv[1]))