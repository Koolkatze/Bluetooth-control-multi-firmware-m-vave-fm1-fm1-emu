static unsigned urban_scale_size(unsigned scale) {
    return urban_scale_sizes[scale%URBAN_SCALE_COUNT];
}
static unsigned urban_scale_pc(unsigned scale,unsigned degree) {
    return urban_scale_intervals[scale%URBAN_SCALE_COUNT][degree%urban_scale_size(scale)];
}
/* Signed degree -> semitone offset, including negative indices.
 * Avoid 7-degree hardcoding across all note, chord and bass engines.
 */
static int urban_scale_offset(unsigned scale,int degree) {
    const int n=(int)urban_scale_size(scale);
    int octave=degree/n,idx=degree%n;
    if(idx<0) {idx+=n;octave--;}
    return 12*octave+(int)urban_scale_pc(scale,(unsigned)idx);
}
/* Remap legacy 7-degree root progressions when a 5/6/8/9/10/12-note
 * scale is selected: preserve relative harmonic tension, do NOT read
 * zero padding or go beyond the scale's actual degree count.
 */
static unsigned urban_scale_root_degree(unsigned scale,unsigned seven_degree) {
    return (seven_degree*urban_scale_size(scale)+3u)/7u;
}
